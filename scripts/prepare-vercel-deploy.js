// Script to prepare for Vercel deployment
const fs = require('fs');
const path = require('path');

console.log('Preparing for Vercel deployment...');

// Ensure .env.production has the database URL
try {
  const envContent = fs.readFileSync('.env', 'utf8');
  const dbUrlMatch = envContent.match(/DATABASE_URL="(.+)"/);
  
  if (dbUrlMatch && dbUrlMatch[1]) {
    const dbUrl = dbUrlMatch[1];
    console.log('Found DATABASE_URL in .env');
    
    // Check if .env.production exists
    const envProdPath = path.join(process.cwd(), '.env.production');
    
    if (!fs.existsSync(envProdPath)) {
      console.log('Creating .env.production file');
      fs.writeFileSync(
        envProdPath,
        `# Auto-generated by prepare-vercel-deploy.js
DATABASE_URL="${dbUrl}"

# Enable debug information for i18n and Prisma in production to troubleshoot
DEBUG_I18N=true
DEBUG_PRISMA=true

# Set additional logging
NODE_OPTIONS="--max-old-space-size=4096"

# Ensure proper Next.js build optimizations
NEXT_TELEMETRY_DISABLED=1
NEXT_SHARP_PATH=/tmp/node_modules/sharp
`
      );
    } else {
      console.log('.env.production already exists, checking if it has DATABASE_URL');
      
      const envProdContent = fs.readFileSync(envProdPath, 'utf8');
      if (!envProdContent.includes('DATABASE_URL=')) {
        console.log('Adding DATABASE_URL to .env.production');
        fs.writeFileSync(
          envProdPath,
          `DATABASE_URL="${dbUrl}"\n${envProdContent}`
        );
      } else {
        console.log('DATABASE_URL already exists in .env.production');
      }
    }
  } else {
    console.warn('Could not find DATABASE_URL in .env file');
  }
} catch (error) {
  console.error('Error processing .env file:', error);
}

// Ensure vercel.json exists
const vercelJsonPath = path.join(process.cwd(), 'vercel.json');
if (!fs.existsSync(vercelJsonPath)) {
  console.log('Creating vercel.json file');
  fs.writeFileSync(
    vercelJsonPath,
    `{
  "framework": "nextjs",
  "buildCommand": "next build",
  "outputDirectory": ".next",
  "regions": ["lhr1"],
  "env": {
    "DEBUG_I18N": "true",
    "DEBUG_PRISMA": "true"
  },
  "headers": [
    {
      "source": "/locales/(.*)",
      "headers": [
        {
          "key": "Cache-Control",
          "value": "public, max-age=3600, s-maxage=3600, stale-while-revalidate=86400"
        }
      ]
    }
  ]
}`
  );
} else {
  console.log('vercel.json already exists');
}

console.log('Deployment preparation complete!');

// Note for the deployer
console.log('\n======= IMPORTANT DEPLOYMENT NOTES =======');
console.log('1. Make sure to set the DATABASE_URL environment variable in Vercel');
console.log('2. Add any necessary auth environment variables (NEXTAUTH_URL, NEXTAUTH_SECRET, etc.)');
console.log('3. If this is a production deployment, consider turning off DEBUG_I18N and DEBUG_PRISMA after verifying everything works');
console.log('======================================\n'); 